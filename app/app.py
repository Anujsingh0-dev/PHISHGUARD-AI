# ── Helper: Load dataset summary ───────────────────────────────────────────────
@st.cache_data
def load_dataset_summary() -> dict:
    """Load saved dataset summary JSON (generated by inspect_dataset.py)."""
    summary_path = METRICS_DIR / "dataset_summary.json"
    if summary_path.exists():
        with open(summary_path, "r") as f:
            return json.load(f)
    return {}


@st.cache_data
def load_full_metrics() -> dict:
    """Load full-model evaluation metrics."""
    try:
        return load_metrics("full_model_metrics.json")
    except FileNotFoundError:
        return {}


@st.cache_data
def load_url_metrics() -> dict:
    """Load URL-model evaluation metrics."""
    try:
        return load_metrics("url_model_metrics.json")
    except FileNotFoundError:
        return {}


@st.cache_data
def load_raw_dataset_sample() -> pd.DataFrame:
    """Load a small sample of the raw dataset for display."""
    if DATASET_CSV.exists():
        return pd.read_csv(DATASET_CSV, nrows=5000)
    return pd.DataFrame()


def load_figure(filename: str):
    """Load a PNG figure if it exists, otherwise return None."""
    path = FIGURES_DIR / filename
    if path.exists():
        return str(path)
    return None


