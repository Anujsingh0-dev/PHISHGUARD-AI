# PAGE 4 — URL DETECTION
# ═══════════════════════════════════════════════════════════════════════════════
def page_url_detection():
    st.markdown("# 🔍 Live URL Detection")
    st.markdown("**Mode B — URL-Only Model**")
    st.markdown(
        '<div class="disclaimer">⚠️ '
        'This tool analyses URL-string features only. '
        'It does <b>not</b> visit the website or download any content. '
        'A "Legitimate" prediction does <b>not</b> mean the website is safe. '
        'Always use caution before sharing personal information online.</div>',
        unsafe_allow_html=True,
    )
    st.markdown("---")

    url_ready, _ = models_are_available()
    if not url_ready:
        st.error(
            "❌ URL model not found.\n\n"
            "Train it first by running:\n"
            "```bash\npython src/train_url_model.py\n```"
        )
        return

    # Input Form (supports clicking button or pressing Enter)
    with st.form("url_input_form", clear_on_submit=False):
        url_input = st.text_input(
            "Enter a URL to analyse:",
            placeholder = "https://www.google.com or paypal-security-update.com/login",
            help        = "Type or paste any URL (e.g., google.com, github.com, or a suspicious link)",
        )
        col_btn, col_sample = st.columns([1, 4])
        with col_btn:
            analyse_clicked = st.form_submit_button("🔍 Analyse URL", use_container_width=True)
        with col_sample:
            st.caption("💡 Examples: `google.com`, `https://github.com`, `http://paypal-security-update.com/login.php`")

    if analyse_clicked:
        if not url_input or not url_input.strip():
            st.warning("Please enter a URL first.")
        else:
            with st.spinner("Analysing URL security indicators & features..."):
                result = predict_url(url_input.strip())

            if result["error"]:
                st.error(f"❌ Error: {result['error']}")
            else:
                st.markdown("---")
                st.markdown("### 📋 Prediction & Security Assessment")

                pred_label  = result["prediction_label"]
                phish_prob  = result["phishing_prob"]
                legit_prob  = result["legitimate_prob"]
                confidence  = result["confidence"]
                risk_level  = result.get("risk_level", "Unknown")
                reasons     = result.get("reasons", [])

                if result["prediction"] == 0:
                    st.markdown(
                        f'<div class="phishing-alert">'
                        f'<h3 style="color:#e74c3c; margin:0;">⚠️ POTENTIALLY PHISHING</h3>'
                        f'<p style="margin:0.5rem 0 0 0; font-weight:bold;">Risk Status: {risk_level}</p>'
                        f'<p style="margin:0.25rem 0 0 0;">This URL shows suspicious characteristics or deceptive patterns.</p>'
                        f'</div>',
                        unsafe_allow_html=True,
                    )
                else:
                    st.markdown(
                        f'<div class="legit-alert">'
                        f'<h3 style="color:#2ecc71; margin:0;">✅ PREDICTED LEGITIMATE</h3>'
                        f'<p style="margin:0.5rem 0 0 0; font-weight:bold;">Risk Status: {risk_level}</p>'
                        f'<p style="margin:0.25rem 0 0 0;">This URL aligns with established legitimate web domain patterns.</p>'
                        f'</div>',
                        unsafe_allow_html=True,
                    )

                # Diagnostic findings
                if reasons:
                    st.markdown("#### 🛡️ Diagnostic Findings")
                    for r in reasons:
                        st.markdown(f"- {r}")

                # Confidence metrics
                if phish_prob is not None:
                    st.markdown("#### 📊 Confidence & Probabilities")
                    col1, col2, col3, col4 = st.columns(4)
                    col1.metric("Classification", pred_label)
                    col2.metric("Risk Level", risk_level)
                    col3.metric("Phishing Prob.", f"{phish_prob*100:.1f}%")
                    col4.metric("Legitimate Prob.", f"{legit_prob*100:.1f}%")

                    # Probability bar
                    fig, ax = plt.subplots(figsize=(8, 1.4))
                    ax.barh(["Phishing"], [phish_prob], color="#e74c3c", alpha=0.85)
                    ax.barh(["Legitimate"], [legit_prob], color="#2ecc71", alpha=0.85)
                    ax.set_xlim(0, 1)
                    ax.set_xlabel("Probability")
                    ax.set_title("Detection Probabilities")
                    plt.tight_layout()
                    st.pyplot(fig)
                    plt.close()

                # Extracted features
                st.markdown("#### 🔬 Extracted URL Features (Mode B)")
                features = result["features"]
                if features:
                    feat_df = pd.DataFrame(
                        list(features.items()), columns=["Feature", "Value"]
                    )
                    st.dataframe(feat_df, use_container_width=True, height=350)

                # Warning
                st.markdown(
                    '<div class="disclaimer">⚠️ '
                    '<b>Important limitation:</b> This prediction is based solely on URL structure. '
                    'Sophisticated phishing sites may use legitimate-looking URLs. '
                    'Legitimate sites may occasionally trigger false positives. '
                    'This model has not been tested on URLs outside the PhiUSIIL dataset distribution.</div>',
                    unsafe_allow_html=True,
                )


