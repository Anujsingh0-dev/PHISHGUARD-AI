# PAGE 3 — MODEL PERFORMANCE
# ═══════════════════════════════════════════════════════════════════════════════
def page_model_performance():
    st.markdown("# 🤖 Model Performance")
    st.markdown("---")

    full_metrics = load_full_metrics()
    url_metrics  = load_url_metrics()

    tab1, tab2 = st.tabs(["📊 Full Dataset Model (Mode A)", "🔗 URL-Only Model (Mode B)"])

    def render_model_tab(metrics: dict, label: str, fig_prefix: str):
        if not metrics:
            st.warning(f"{label} metrics not found. Train the model first.")
            return

        all_models = metrics.get("metrics", {}).get("all_models", [])
        best_name  = metrics.get("metrics", {}).get("best_model", "")

        if not all_models:
            st.warning("No model results found.")
            return

        # Comparison table
        st.markdown("### Model Comparison")
        rows = []
        for m in all_models:
            rows.append({
                "Model"    : m["model_name"],
                "Accuracy" : m.get("accuracy",  0),
                "Precision": m.get("precision", 0),
                "Recall"   : m.get("recall",    0),
                "F1-Score" : m.get("f1_score",  0),
                "ROC-AUC"  : m.get("roc_auc",   None),
            })
        comp_df = pd.DataFrame(rows)
        st.dataframe(comp_df.style.highlight_max(subset=["Accuracy","Precision","Recall","F1-Score"], color="#1c3d2a"), use_container_width=True)
        st.caption(f"✅ Best model (by F1-score): **{best_name}**")

        st.markdown("---")

        col_a, col_b = st.columns(2)

        with col_a:
            st.markdown("### Confusion Matrix")
            cm_fig = load_figure(f"cm_{best_name.lower().replace(' ', '_')}.png") if fig_prefix == "full" else load_figure("url_model_confusion_matrix.png")
            if cm_fig:
                st.image(cm_fig, use_container_width=True)
                st.markdown("""
**Reading the confusion matrix:**
- **True Positive (TP):** Phishing predicted as Phishing ✅
- **True Negative (TN):** Legitimate predicted as Legitimate ✅
- **False Positive (FP):** Legitimate predicted as Phishing ⚠️ (inconvenient)
- **False Negative (FN):** Phishing predicted as Legitimate ❌ (dangerous!)
                """)
            else:
                st.info("Train the model to generate this chart.")

        with col_b:
            st.markdown("### ROC Curve")
            roc_fig = load_figure(f"{fig_prefix}_model_roc_curve.png")
            if roc_fig:
                st.image(roc_fig, use_container_width=True)
                st.markdown(
                    "The ROC curve shows the trade-off between True Positive Rate and False Positive Rate. "
                    "A curve closer to the top-left corner is better. AUC = Area Under Curve (max = 1.0)."
                )
            else:
                st.info("Train the model to generate this chart.")

        st.markdown("### Feature Importance")
        imp_fig = load_figure(f"{fig_prefix}_model_feature_importance.png")
        if imp_fig:
            st.image(imp_fig, use_container_width=True)
            st.markdown(
                "Feature importance shows which attributes contribute most to the model's decisions. "
                "Higher importance = more influence on the prediction."
            )
        else:
            st.info("Train a tree-based model to generate this chart.")

    with tab1:
        render_model_tab(full_metrics, "Full Dataset Model", "full")

    with tab2:
        render_model_tab(url_metrics,  "URL-Only Model",     "url")
        st.markdown(
            '<div class="disclaimer">⚠️ '
            'The URL-only model uses only URL-string features. '
            'It cannot analyse webpage content, SSL certificates, or hosting information. '
            'Its accuracy is expected to be lower than the full-dataset model. '
            'This is honest by design.</div>',
            unsafe_allow_html=True,
        )


